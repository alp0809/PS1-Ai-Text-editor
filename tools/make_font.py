#!/usr/bin/env python3
"""
make_font.py - builds ps1/font_latin1.h, the 8x8 font of the PS1 editor.

The glyphs come from font8x8 by Daniel Hepper (public domain,
https://github.com/dhepper/font8x8): "basic" for 0x20-0x7F and "ext_latin"
for 0xA0-0xFF, which together cover ISO-8859-1 (Latin-1).

    python3 tools/make_font.py path/to/font8x8 > ps1/font_latin1.h

Each glyph is 8 rows; bit 0 of a row is the leftmost pixel.
"""
import re
import sys

def load(path):
    rows = []
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\s*\{([^}]*)\}", line)
        if m:
            rows.append([int(v, 16) for v in m.group(1).split(",")])
    return rows


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "font8x8"
    basic = load(f"{src}/font8x8_basic.h")      # U+0000..U+007F
    ext = load(f"{src}/font8x8_ext_latin.h")    # U+00A0..U+00FF
    assert len(basic) == 128 and len(ext) == 96

    font = [[0] * 8 for _ in range(256)]
    for c in range(0x20, 0x7F):
        font[c] = basic[c]
    for c in range(0xA0, 0x100):
        font[c] = ext[c - 0xA0]
    # 0x7F and 0x80..0x9F: a small box, so stray bytes are visible
    box = [0x00, 0x3E, 0x22, 0x22, 0x22, 0x22, 0x3E, 0x00]
    font[0x7F] = box
    for c in range(0x80, 0xA0):
        font[c] = box

    out = sys.stdout
    out.write("/* font_latin1.h - generated by tools/make_font.py, do not edit.\n"
              " * 8x8 glyphs for ISO-8859-1, from font8x8 by Daniel Hepper (public\n"
              " * domain). Bit 0 = leftmost pixel. */\n\n")
    out.write("#ifndef FONT_LATIN1_H\n#define FONT_LATIN1_H\n\n#include <stdint.h>\n\n")
    out.write("static const uint8_t font_latin1[256][8] = {\n")
    for c in range(256):
        name = chr(c) if 0x20 < c < 0x7F else ""
        vals = ", ".join(f"0x{v:02X}" for v in font[c])
        out.write(f"\t{{ {vals} }},  /* {c:02X} {name.replace('*/', '')} */\n")
    out.write("};\n\n#endif\n")


if __name__ == "__main__":
    main()
